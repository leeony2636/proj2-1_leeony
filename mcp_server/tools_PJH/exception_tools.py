from datetime import datetime


# ==========================================================
# MCP 도구: report_equipment_issue
#
# 주의: "안 열리네" 같은 발화를 보고 원인이 무엇인지(정답오류/자물쇠오인/
#       사용법미숙/실제 기구이상) 구분하는 것은 LLM이 하는 일이다.
#       이 함수는 그 구분 결과(원인)를 넘겨받아서, 실제 기구 이상일 때만
#       MASTER_REQUEST로 전환하는 최종 결정만 담당한다.
# ==========================================================

def report_equipment_issue(세션_ID, 문제번호, 원인, 지금시각):
    """
    손님 발화의 원인 구분 결과를 받아서, 기구 이상이면 직원 호출로 전환한다.

    입력:
        세션_ID   - "S-001" 같은 세션 고유번호
        문제번호   - 원인이 발생한 문제 (내부 기록용. 손님에게는 노출 안 함)
        원인      - LLM이 구분한 원인. 다음 네 가지 중 하나:
                    "정답오류" / "자물쇠오인" / "사용법미숙" / "기구이상"
        지금시각   - datetime 값 (기록 시각)

    출력:
        {
            "status": "OK",
            "next_action": "MASTER_REQUEST" 또는 "CONTINUE_HINT_FLOW",
            "event": {...}   # 내부 기록용 이벤트 (puzzle_id 포함, 손님에게 노출 안 함)
        }
    """

    # 실제 기구 이상일 때만 직원 호출로 전환한다.
    if 원인 == "기구이상":
        다음_행동 = "MASTER_REQUEST"
    else:
        # 정답오류/자물쇠오인/사용법미숙은 기구 문제가 아니므로
        # 힌트 판단 흐름을 계속 진행한다 (직원을 부를 필요 없음).
        다음_행동 = "CONTINUE_HINT_FLOW"

    이벤트_기록 = {
        "session_id": 세션_ID,
        "puzzle_id": 문제번호,     # 내부 기록용. 손님 응답에는 포함하지 않는다.
        "reported_cause": 원인,
        "reported_at": 지금시각,
    }

    return {
        "status": "OK",
        "next_action": 다음_행동,
        "event": 이벤트_기록,
    }


# ==========================================================
# MCP 도구: request_game_master
#
# 화면에 상시로 떠 있는 "직원 호출" 버튼을 눌렀을 때 호출되는 함수.
# report_equipment_issue와 달리, 원인을 구분할 필요 없이
# 손님이 버튼을 눌렀다는 사실 자체가 곧바로 직원 호출로 이어진다.
# (조건 분기가 없는 단순한 함수 — 버튼 = 무조건 호출)
# ==========================================================

def request_game_master(세션_ID, 지금시각):
    """
    손님이 "직원 호출" 버튼을 직접 눌렀을 때 호출되는 함수.
    조건 판단 없이, 누르는 즉시 직원 호출로 전환한다.

    입력:
        세션_ID   - "S-001" 같은 세션 고유번호
        지금시각   - datetime 값 (기록 시각)

    출력:
        {
            "status": "OK",
            "next_action": "MASTER_REQUEST",
            "event": {...}
        }
    """

    이벤트_기록 = {
        "session_id": 세션_ID,
        "requested_at": 지금시각,
        "trigger": "BUTTON",   # 버튼으로 호출됐음을 기록 (자동감지와 구분하기 위해)
    }

    return {
        "status": "OK",
        "next_action": "MASTER_REQUEST",
        "event": 이벤트_기록,
    }


# ==========================================================
# 테스트 코드
# ==========================================================

if __name__ == "__main__":
    print("===== report_equipment_issue 테스트 =====")

    # 시나리오 1: 실제 기구 이상 → 직원 호출로 전환돼야 함
    결과 = report_equipment_issue(
        세션_ID="S-001",
        문제번호="P05",
        원인="기구이상",
        지금시각=datetime(2026, 9, 19, 14, 30, 0),
    )
    print("기구이상 신고:", 결과["next_action"])

    # 시나리오 2: 자물쇠 오인 → 힌트 흐름 계속 (직원 호출 안 함)
    결과 = report_equipment_issue(
        세션_ID="S-001",
        문제번호="P05",
        원인="자물쇠오인",
        지금시각=datetime(2026, 9, 19, 14, 31, 0),
    )
    print("자물쇠오인:", 결과["next_action"])

    print()
    print("===== request_game_master 테스트 =====")

    # 시나리오: 손님이 버튼을 직접 누름 → 무조건 직원 호출
    결과 = request_game_master(
        세션_ID="S-001",
        지금시각=datetime(2026, 9, 19, 14, 35, 0),
    )
    print("버튼 호출:", 결과["next_action"])
    print("기록된 이벤트:", 결과["event"])
