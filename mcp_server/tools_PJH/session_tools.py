# ==========================================================
# MCP 도구: record_hint_delivery
#
# 손님에게 힌트를 실제로 제공한 뒤, 그 사실을 힌트_이력 리스트에 추가하는 함수.
# 이렇게 기록해둬야, 다음번에 get_hint_history가 "재요청인지" 판단할 수 있다.
# ==========================================================

def record_hint_delivery(힌트_이력, 문제번호, 힌트강도, 지금시각):
    """
    힌트를 제공했다는 사실을 힌트_이력 리스트 맨 뒤에 추가한다.

    입력:
        힌트_이력   - 예시_힌트_이력 같은 리스트 (이 함수가 직접 여기에 추가한다)
        문제번호    - 방금 힌트를 제공한 문제 (내부 기록용)
        힌트강도    - "weak" 또는 "strong"
        지금시각    - datetime 값 (기록 시각)

    출력:
        {
            "status": "OK",
            "recorded_event": {...}   # 방금 추가된 기록 (내부 확인용)
        }

    주의: 이 함수는 힌트_이력 리스트 자체를 직접 바꾼다(append).
         새 리스트를 만들어서 돌려주는 게 아니라, 원래 리스트 뒤에 이어붙인다.
    """

    새_기록 = {
        "puzzle_id": 문제번호,
        "hint_strength": 힌트강도,
        "delivered_at": 지금시각,
    }

    # 리스트 맨 뒤에 새 기록을 추가한다.
    힌트_이력.append(새_기록)

    return {
        "status": "OK",
        "recorded_event": 새_기록,
    }


