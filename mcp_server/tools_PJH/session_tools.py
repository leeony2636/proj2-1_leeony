# MCP 도구: get_hint_history
# "지금 요청이 재요청인지 아닌지"를 판단해서 돌려주는 함수
# ==========================================================

def get_hint_history(힌트_이력, 지금_문제번호, 지금시각):
    """
    직전 힌트 기록을 보고, 지금 요청이 "재요청 오버라이드" 조건에
    해당하는지 판단한다.

    재요청 오버라이드 조건 (SKILL.md 기준):
        - 직전 힌트가 "약한 힌트"였고
        - 직전 힌트와 같은 문제에 대한 요청이고
        - 직전 힌트 시각으로부터 1분 이내인 경우

    입력:
        힌트_이력      - 예시_힌트_이력 같은 리스트 (지금까지 준 힌트 기록들)
        지금_문제번호   - 지금 손님이 묻고 있는 문제번호 (예: "P04")
        지금시각        - datetime 값

    출력:
        {
            "status": "OK",
            "is_re_request": True 또는 False,
            "last_hint": {...} 또는 None   # 참고용으로 직전 힌트 기록도 같이 돌려줌
        }
    """

    # 1) 힌트 이력이 하나도 없으면, 재요청일 수가 없다.
    if len(힌트_이력) == 0:
        return {
            "status": "OK",
            "is_re_request": False,
            "last_hint": None,
        }

    # 2) 이력 중 "가장 최근" 기록을 찾는다.
    #    이력은 시간 순서대로 쌓인다고 가정하고, 리스트의 마지막 항목이 가장 최근이다.
    직전_힌트 = 힌트_이력[-1]   # 리스트의 마지막 항목을 가져오는 문법

    # 3) 조건 하나씩 확인한다.

    # 조건 1: 직전 힌트가 약한 힌트였는가?
    직전이_약한힌트인가 = (직전_힌트["hint_strength"] == "weak")

    # 조건 2: 같은 문제에 대한 요청인가?
    같은_문제인가 = (직전_힌트["puzzle_id"] == 지금_문제번호)

    # 조건 3: 1분(60초) 이내인가?
    시간차이 = 지금시각 - 직전_힌트["delivered_at"]
    시간차이_초 = 시간차이.total_seconds()
    일분_이내인가 = (시간차이_초 <= 60)

    # 4) 세 조건이 모두 참이어야 "재요청"으로 판단한다.
    if 직전이_약한힌트인가 and 같은_문제인가 and 일분_이내인가:
        재요청여부 = True
    else:
        재요청여부 = False

    return {
        "status": "OK",
        "is_re_request": 재요청여부,
        "last_hint": 직전_힌트,
    }


