    # 시나리오 1: P04에 14시 25분 약한 힌트를 줬고, 손님이 14시 25분 40초에 같은 문제로 다시 물어봄
    #            → 같은 문제 + 40초(1분 이내) + 직전이 약함 → 재요청 True 여야 함
    지금 = datetime(2026, 9, 19, 14, 25, 40)
