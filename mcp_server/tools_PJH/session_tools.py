# 세션 데이터 (가짜 DB 역할)
# 손님 한 팀이 입장하면 이런 형태의 딕셔너리가 하나 생긴다고 가정한다.
# 세션이 끝나면(다음 손님이 오면) 이 데이터는 사라지고 새로 만들어진다.
# ==========================================================

예시_세션 = {
    "session_id": "S-001",
    "theme_id": "THEME_01",              # 어느 테마로 진행 중인지 (교수님의 연구실)
    "started_at": datetime(2026, 9, 19, 14, 0, 0),  # 세션 시작 시각 (14시 정각에 시작했다고 가정)
    "time_limit_minutes": 60,             # 제한시간 60분
    "solved_puzzles": 3,                  # 지금까지 3문제를 풀었다고 가정
}


# ==========================================================
# MCP 도구: get_game_session
# 세션의 "남은시간"과 "진도율"을 계산해서 돌려주는 함수
# ==========================================================

def get_game_session(세션, 전체_문제_수, 지금시각):
    """
    세션 정보를 받아서 남은시간(분)과 진도율을 계산해 돌려준다.

    입력:
        세션          - 예시_세션 같은 딕셔너리 (started_at, time_limit_minutes, solved_puzzles 포함)
        전체_문제_수   - 이 테마의 total_puzzles 값 (예: 12)
        지금시각       - datetime 값. "지금이 몇 시인지"를 알려줌

    출력:
        {
            "status": "OK",
            "session_id": "S-001",
            "remaining_time_minutes": 45.0,
            "remaining_puzzle_ratio": 0.75
        }
    """

    # 1) 시작시각부터 지금시각까지 얼마나 지났는지 계산한다.
    경과시간 = 지금시각 - 세션["started_at"]

    # 경과시간은 처음엔 "초" 단위로 나오기 때문에, 60으로 나눠서 "분" 단위로 바꾼다.
    경과시간_분 = 경과시간.total_seconds() / 60

    # 2) 남은시간 = 제한시간 - 경과시간
    남은시간_분 = 세션["time_limit_minutes"] - 경과시간_분

    # 시간이 다 지나서 마이너스가 나오는 경우, 0으로 고정한다. (음수 시간은 의미가 없으므로)
    if 남은시간_분 < 0:
        남은시간_분 = 0

    # 3) 남은 문제 비율을 계산한다.
    #    진도율(해결한 비율)이 아니라, SKILL.md·기획안 기준은 "남은 문제 비율"이므로
    #    이 함수는 remaining_puzzle_ratio(남은 비율)를 돌려준다.
    해결한_문제_수 = 세션["solved_puzzles"]
    남은_문제_수 = 전체_문제_수 - 해결한_문제_수
    남은_문제_비율 = 남은_문제_수 / 전체_문제_수

    # 4) 결과를 딕셔너리로 정리해서 돌려준다.
    return {
        "status": "OK",
        "session_id": 세션["session_id"],
        "remaining_time_minutes": round(남은시간_분, 1),   # 소수점 첫째자리까지만 반올림
        "remaining_puzzle_ratio": round(남은_문제_비율, 2),  # 소수점 둘째자리까지만 반올림
    }


