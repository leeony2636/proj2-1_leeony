def 문제_찾기(테마, 찾을_문제번호):
    """
    테마 데이터 안에서 puzzle_id가 일치하는 문제 하나를 찾아 돌려주는 함수.
    없으면 None을 돌려준다.
    """
    for 문제 in 테마["puzzles"]:
        if 문제["puzzle_id"] == 찾을_문제번호:
            return 문제
    return None


def 문제_개수_확인(테마):
    """
    puzzles 리스트에 실제로 몇 개가 들어있는지 세어서,
    total_puzzles와 일치하는지 확인하는 함수.
    """
    실제_개수 = 0
    for 문제 in 테마["puzzles"]:
        실제_개수 = 실제_개수 + 1
    return 실제_개수


def 재활용_문제_목록(테마):
    """
    note 필드가 채워진(=단서 재활용이나 다중조합이 있는) 문제만 골라서
    리스트로 돌려주는 함수.
    """
    결과 = []
    for 문제 in 테마["puzzles"]:
        if 문제["note"] is not None:
            결과.append(문제)
    return 결과


